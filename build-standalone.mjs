// Builds orbit-standalone.html: the whole app in ONE file that also opens with a double-click
// (no server needed for the 3D view; the AI chat still needs the server). Run:  node build-standalone.mjs
// 生成单文件版本 orbit-standalone.html。Optional: the website itself doesn't need this file.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.dirname(fileURLToPath(import.meta.url));
const ORDER = ['i18n', 'data', 'noise', 'textures', 'maps', 'bodies', 'highlights', 'habitability', 'gestures', 'voice', 'narration-text', 'narration', 'chat', 'main'];
const read = f => fs.readFileSync(path.join(root, f), 'utf8');

function convert(name, src) {
  const exported = [];
  const code = src
    .replace(/^import \* as T from 'three';\s*$/m, '')
    .replace(/^import\s*\{([^}]*)\}\s*from\s*'\.\/([\w-]+)\.js';\s*$/gm, (_, names, mod) =>
      `const { ${names.split(',').map(n => n.trim()).filter(Boolean).map(n => n.replace(/\s+as\s+/, ': ')).join(', ')} } = __m['${mod}'];`)
    .replace(/^export\s+(async\s+function|function|const|let|class)\s+([\w$]+)/gm, (_, kind, id) => { exported.push(id); return `${kind} ${id}`; });
  return `__m['${name}'] = (() => {\n${code}\nreturn { ${exported.join(', ')} };\n})();\n`;
}
const esc = s => s.replace(/<\/script/gi, '<\\/script');
const modules = ORDER.map(n => convert(n, read(n + '.js'))).join('\n');
let html = read('index.html');
html = html.replace('<link rel="stylesheet" href="style.css">', () => `<style>\n${read('style.css')}\n</style>`);
html = html.replace('<link rel="stylesheet" href="asteroids.css">', () => `<style>\n${read('asteroids.css')}\n</style>`);
html = html.replace('<script type="module" src="main.js"></script>', () =>
  `<script type="module">\n// Generated by build-standalone.mjs. Edit the .js files, then run: node build-standalone.mjs\nimport * as T from 'three';\nconst __m = {};\n${esc(modules)}</script>`);
html = html.replace('<script src="asteroids.js" defer></script>', () =>
  `<script id="astorbCatalogData" type="application/json">${esc(read('astorb.json'))}</script>\n<script>\n${esc(read('asteroids.js'))}\n</script>`);
html = html.replace('<script src="resources.js" defer></script>', () => `<script>\n${esc(read('resources.js'))}\n</script>`);
// Music: embed each music-<scene>.mp3 as base64 so the single file plays offline.
const audio = {};
for (const f of fs.readdirSync(root)) { const m = f.match(/^music-([\w-]+)\.mp3$/); if (m) audio[m[1]] = fs.readFileSync(path.join(root, f)).toString('base64'); }
html = html.replace('<script src="music.js" defer></script>', () =>
  `<script id="stellarAudioData" type="application/json">${JSON.stringify(audio)}</script>\n<script>\n${esc(read('music.js'))}\n</script>`);
// Embed the surface maps so the single file needs no other files.
const MIME = { '.jpg': 'image/jpeg', '.jpeg': 'image/jpeg', '.png': 'image/png', '.webp': 'image/webp' }, tex = {};
for (const f of fs.readdirSync(root)) {
  const ext = path.extname(f).toLowerCase(); if (!MIME[ext]) continue;
  tex[path.basename(f, ext)] = `data:${MIME[ext]};base64,` + fs.readFileSync(path.join(root, f)).toString('base64');
}
html = html.replace('<script type="module">', () => `<script>window.__ORBIT_TEXTURES = ${JSON.stringify(tex)};</script>\n<script type="module">`);
fs.writeFileSync(path.join(root, 'orbit-standalone.html'), html);
console.log('Wrote orbit-standalone.html (' + (html.length / 1048576).toFixed(1) + ' MB, ' + Object.keys(tex).length + ' surface maps)');
